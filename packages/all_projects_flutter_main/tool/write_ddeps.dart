import 'dart:io';

import 'package:path/path.dart';
import 'package:process_run/shell.dart';

/// Write the `ddeps list` output of this package in doc/.
///
/// dart run tool/write_ddeps.dart [--tekartik] [--json]
///
/// --tekartik only keeps the tekartik packages (git or published), written to
/// doc/ddeps_tekartik.md instead of doc/ddeps.md.
/// --json writes the json format instead (the packages bottom up with their
/// level, 0 without dependencies) to a .json file.
Future<void> main(List<String> arguments) async {
  var options = ['--tekartik', '--json'];
  var unknown = arguments.where((argument) => !options.contains(argument));
  if (unknown.isNotEmpty) {
    stderr.writeln('Unknown arguments: ${unknown.join(' ')}');
    stderr.writeln(
      'Usage: dart run tool/write_ddeps.dart ${options.map((option) => '[$option]').join(' ')}',
    );
    exitCode = 64;
    return;
  }
  var tekartik = arguments.contains('--tekartik');
  var json = arguments.contains('--json');
  var ddepsArguments = ['list', if (tekartik) '--tekartik', if (json) '--json'];

  var results = await Shell(
    verbose: false,
  ).run('ddeps ${shellArguments(ddepsArguments)}');
  var output = '${results.outText.trimRight()}\n';

  var baseName = tekartik ? 'ddeps_tekartik' : 'ddeps';
  String content;
  String fileName;
  if (json) {
    fileName = '$baseName.json';
    content = output;
  } else {
    fileName = '$baseName.md';
    content =
        '# ddeps ${ddepsArguments.join(' ')}\n'
        '\n'
        'Generated by `dart run tool/write_ddeps.dart${tekartik ? ' --tekartik' : ''}`.\n'
        '\n'
        '```text\n'
        '$output'
        '```\n';
  }
  var file = File(join('doc', fileName));
  await file.parent.create(recursive: true);
  await file.writeAsString(content);
  stdout.writeln('Wrote ${file.path}');
}
